def view_checkpoint_history(agent, config):
    """View all checkpoints for a thread"""
    logger.info(f"\n{'='*50}")
    logger.info(f"📜 CHECKPOINT HISTORY")
    logger.info(f"{'='*50}")
    
    try:
        history = list(agent.get_state_history(config))
    except Exception as e:
        logger.error(f"Error getting checkpoint history: {e}")
        return
    
    for i, state_snapshot in enumerate(reversed(history)):
        logger.info(f"\nCheckpoint #{i+1}:")
        logger.info(f"  Next node: {state_snapshot.next}")
        logger.info(f"  Attempt: {state_snapshot.values.get('planning_attempt_count', 0)}")
        logger.info(f"  Valid: {state_snapshot.values.get('is_valid', 'N/A')}")
        
        if state_snapshot.values.get('validation_issues'):
            logger.info(f"  Issues: {len(state_snapshot.values['validation_issues'])}")
    
    logger.info(f"\n{'='*50}\n")


def resume_from_checkpoint(agent, config):
    """Resume execution from last checkpoint"""
    logger.info("🔄 Resuming from last checkpoint...")
    
    # Get current state
    current_state = agent.get_state(config)
    logger.info(f"Last node: {current_state.next}")
    logger.info(f"Current state keys: {list(current_state.values.keys())}")
    
    # Resume execution
    result = agent.invoke(None, config)
    return result


